#!/usr/bin/env python3
"""Requirement traceability: does every FSD requirement have a test, and did it pass?

Reads the requirements table in docs/FSD.md:

    | ID | Requirement | Tier | Test |
    | REQ-010 | Text wraps at word boundaries. | host | wrap_* |

finds each named test in the code for its tier, and looks up the result of the
last run of that tier:

    tier     test is found in                       last result read from
    host     TEST(name) in test/host/*.cpp          build/host-test.log   (make host-test)
    target   report("T-XXX", ...) in firmware/      build/target-test.log (make target-test)
    bench    def test_xxx in test/bench/test_*.py   build/bench-test.xml  (make bench-test)
    field / manual   nothing to find: a human checks it (FSD section 8)

The Test column may hold several names separated by commas, and shell-style
wildcards (wrap_*). Usage:

    trace.py                       print the matrix (always exits 0)
    trace.py --strict              exit 1 if a requirement has no test or a test FAILED
    trace.py --require-run         like --strict, and NOT RUN / SKIPPED also fail
    trace.py REQ-010 REQ-020 ...   only these requirements (e.g. the current phase)
    trace.py --out docs/STATUS.md  also write the matrix as a Markdown file

Results are tied to the code they were produced from. Each tier's result carries
a fingerprint of its source (host: logic + host tests; target and bench: the
firmware build id the board itself reports). If the source changed since, the
requirement shows STALE instead of PASS, and --require-run fails.

A target test can be demanded per board: `T-TOUCH@R, T-TOUCH@C` in the Test
column needs a pass in build/target-test.R.log AND build/target-test.C.log
(written when the board is registered, see tools/esp_serial.py register).

Helpers used by the Makefile:

    trace.py --hash host|firmware|bench     print the current source fingerprint
    trace.py --write-build-id FILE          write FW_BUILD_ID for the firmware build

This is the "did we build what we specified?" check. A green matrix is evidence
that the firmware does what the FSD says, as far as the tests go.
"""

from __future__ import annotations

import argparse
import fnmatch
import hashlib
import re
import sys
import time
import xml.etree.ElementTree as ET
from dataclasses import dataclass, field
from pathlib import Path

AUTO_TIERS = ("host", "target", "bench")
HUMAN_TIERS = ("field", "manual")

PASS, FAIL, SKIP, NOT_RUN, NO_TEST, HUMAN, BAD_TIER, STALE = (
    "PASS", "FAIL", "SKIPPED", "NOT RUN", "NO TEST", "MANUAL", "BAD TIER", "STALE")
BLOCKING_STRICT = {FAIL, NO_TEST, BAD_TIER}
BLOCKING_RUN = BLOCKING_STRICT | {NOT_RUN, SKIP, STALE}

# ------------------------------------------------------- source fingerprints
# What each tier's result depends on. Generated files, caches and the
# git-ignored secrets file are left out, so the fingerprint is the same on the
# dev box and in CI for the same commit.
SOURCES = {
    "host": ("firmware/src/logic", "test/host"),
    "firmware": ("firmware",),
    "bench": ("test/bench",),
}
BUILD_ID_HEADER = "build_id.h"
_SKIP_DIRS = {"__pycache__", ".pytest_cache", "build"}
_SKIP_FILES = {BUILD_ID_HEADER, "secrets.h"}


def src_hash(root: Path, what: str) -> str:
    """12-hex-digit fingerprint of the files behind one tier (see SOURCES)."""
    files = set()
    for sub in SOURCES[what]:
        base = root / sub
        if base.is_dir():
            files.update(p for p in base.rglob("*") if p.is_file()
                         and not _SKIP_DIRS.intersection(p.relative_to(root).parts)
                         and p.name not in _SKIP_FILES and p.suffix != ".pyc")
    digest = hashlib.sha256()
    for p in sorted(files):
        digest.update(p.relative_to(root).as_posix().encode() + b"\0")
        digest.update(p.read_bytes() + b"\0")
    return digest.hexdigest()[:12]


def write_build_id(root: Path, header: Path) -> str:
    """Write the firmware's fingerprint as FW_BUILD_ID (only if it changed, so an
    unchanged tree does not trigger a rebuild)."""
    build_id = src_hash(root, "firmware")
    text = ("// Generated by tools/trace.py at compile time. Do not edit or commit.\n"
            f'#pragma once\n#define FW_BUILD_ID "{build_id}"\n')
    if not header.is_file() or header.read_text(encoding="utf-8") != text:
        header.parent.mkdir(parents=True, exist_ok=True)
        header.write_text(text, encoding="utf-8")
    return build_id


@dataclass
class Requirement:
    rid: str
    text: str
    tier: str
    tests: list[str]
    matched: list[str] = field(default_factory=list)
    status: str = NOT_RUN
    detail: str = ""


# ---------------------------------------------------------------- FSD parsing
_REQ_ROW = re.compile(r"^\s*\|\s*(REQ-[0-9A-Za-z_.-]+)\s*\|(.*)\|\s*$")


def parse_fsd(text: str) -> list[Requirement]:
    """Requirement rows from the FSD's Markdown table(s). Placeholder rows such as
    '| REQ-… | | | |' (no requirement text) are ignored."""
    reqs = []
    for line in text.splitlines():
        m = _REQ_ROW.match(line)
        if not m:
            continue
        cells = [c.strip() for c in m.group(2).split("|")]
        if len(cells) < 3 or not cells[0]:
            continue
        req_text, tier, test = cells[0], cells[1].lower(), cells[2]
        tests = [t.strip().strip("`") for t in re.split(r"[,;]|\s+", test) if t.strip().strip("`")]
        reqs.append(Requirement(m.group(1), req_text, tier, tests))
    return reqs


# ------------------------------------------------------------ test discovery
def _read_all(paths) -> str:
    return "\n".join(p.read_text(encoding="utf-8", errors="replace") for p in paths if p.is_file())


def discover(root: Path) -> dict[str, set[str]]:
    host_src = _read_all(sorted((root / "test" / "host").glob("*.cpp")))
    fw = root / "firmware"
    target_src = _read_all(sorted(list(fw.rglob("*.cpp")) + list(fw.rglob("*.ino")))) if fw.is_dir() else ""
    bench_src = _read_all(sorted((root / "test" / "bench").glob("test_*.py")))
    return {
        "host": set(re.findall(r"\bTEST\(\s*(\w+)\s*\)", host_src)),
        "target": set(re.findall(r"\breport\(\s*\"(T-[\w-]+)\"", target_src)),
        "bench": set(re.findall(r"^\s*(?:async\s+)?def\s+(test_\w+)\s*\(", bench_src, re.M)),
    }


# --------------------------------------------------------------- last results
def load_results(root: Path) -> tuple[dict[str, dict[str, str]], dict[str, str], dict[str, dict[str, str]]]:
    """Returns three dicts:
    results  {tier: {test: PASS|FAIL|SKIPPED}}
    when     {tier: 'file @ time' of the evidence}
    stale    {tier: {test: why this result no longer matches the source}}
    Target tests appear as 'T-X' (last run, any board) and 'T-X@R' / 'T-X@C'
    (last run on that registered board)."""
    build = root / "build"
    results: dict[str, dict[str, str]] = {t: {} for t in AUTO_TIERS}
    stale: dict[str, dict[str, str]] = {t: {} for t in AUTO_TIERS}
    when: dict[str, str] = {}

    def stamp(p: Path) -> str:
        return f"{p.relative_to(root)} @ {time.strftime('%Y-%m-%d %H:%M', time.localtime(p.stat().st_mtime))}"

    host = build / "host-test.log"
    if host.is_file():
        txt = host.read_text(errors="replace")
        for m in re.finditer(r"^HOSTTEST:(\w+):(PASS|FAIL)$", txt, re.M):
            results["host"][m.group(1)] = m.group(2)
        when["host"] = stamp(host)
        m = re.search(r"^SRC:(\w+)$", txt, re.M)
        if not m or m.group(1) != src_hash(root, "host"):
            when["host"] += " (STALE)"
            for name in results["host"]:
                stale["host"][name] = "logic or host tests changed since the last `make host-test`"

    fw_now = src_hash(root, "firmware")

    def fw_stale(build_id: str | None, rerun: str) -> str | None:
        if not build_id:
            return f"result does not say which firmware build it tested; rerun `{rerun}`"
        if build_id != fw_now:
            return (f"tested firmware build {build_id}, the source is now {fw_now}; "
                    f"rerun `{rerun}`")
        return None

    target_notes = []
    for log in [build / "target-test.log"] + sorted(build.glob("target-test.*.log")):
        if not log.is_file():
            continue
        board = log.name[len("target-test."):-len(".log")] if log.name != "target-test.log" else ""
        suffix = f"@{board.upper()}" if board else ""
        txt = log.read_text(errors="replace")
        m = re.search(r"^SELFTEST:BEGIN build=(\w+)", txt, re.M)
        why = fw_stale(m.group(1) if m else None,
                       f"make loop BOARD={board.upper()}" if board else "make loop")
        for m in re.finditer(r"^TEST:([\w-]+):(PASS|FAIL):", txt, re.M):
            results["target"][m.group(1) + suffix] = m.group(2)
            if why:
                stale["target"][m.group(1) + suffix] = why
        target_notes.append(stamp(log) + (" (CRASHED)" if "SELFTEST:CRASH" in txt else "")
                            + (" (STALE)" if why else ""))
    if target_notes:
        when["target"] = "; ".join(target_notes)

    bench = build / "bench-test.xml"
    if bench.is_file():
        try:
            for case in ET.parse(bench).getroot().iter("testcase"):
                name = case.get("name", "").split("[", 1)[0]  # drop pytest parameter ids
                tags = {child.tag for child in case}
                status = FAIL if tags & {"failure", "error"} else SKIP if "skipped" in tags else PASS
                if results["bench"].get(name) != FAIL:  # a failing parameter wins
                    results["bench"][name] = status
            when["bench"] = stamp(bench)
        except ET.ParseError:
            when["bench"] = f"{bench.relative_to(root)} (unreadable)"
        stamp_file = build / "bench-test.stamp"
        fields = dict(kv.split("=", 1) for kv in
                      (stamp_file.read_text(errors="replace").split() if stamp_file.is_file() else [])
                      if "=" in kv)
        why = fw_stale(fields.get("fw") or None, "make loop && make bench-test")
        if not why and fields.get("tests") != src_hash(root, "bench"):
            why = "bench tests changed since the last `make bench-test`"
        if why:
            when["bench"] = when.get("bench", "") + " (STALE)"
            for name in results["bench"]:
                stale["bench"][name] = why
    return results, when, stale


# ---------------------------------------------------------------- evaluation
def evaluate(reqs: list[Requirement], found: dict[str, set[str]],
             results: dict[str, dict[str, str]],
             stale: dict[str, dict[str, str]] | None = None) -> None:
    stale = stale or {}
    for r in reqs:
        if r.tier in HUMAN_TIERS:
            r.status, r.detail = HUMAN, "checked by a person (FSD section 8)"
            continue
        if r.tier not in AUTO_TIERS:
            r.status, r.detail = BAD_TIER, f"tier '{r.tier}' is not host/target/bench/field/manual"
            continue
        names = found[r.tier]
        missing = []
        for pattern in r.tests:
            # 'T-TOUCH@C' = target test T-TOUCH, proven on the board registered as C.
            base, at, board = pattern.partition("@")
            if at and r.tier != "target":
                hits = []
            else:
                hits = [h + at + board.upper() for h in sorted(fnmatch.filter(names, base))]
            if hits:
                r.matched.extend(h for h in hits if h not in r.matched)
            else:
                missing.append(pattern)
        if not r.tests or missing:
            elsewhere = [t for t in missing for tier, n in found.items()
                         if tier != r.tier and fnmatch.filter(n, t.partition("@")[0])]
            hint = f" (exists in another tier: {', '.join(elsewhere)})" if elsewhere else ""
            r.status = NO_TEST
            r.detail = (f"no {r.tier} test named {', '.join(missing)}{hint}" if missing
                        else "Test column is empty")
            continue
        got = [results[r.tier].get(t, NOT_RUN) for t in r.matched]
        failed = [t for t, s in zip(r.matched, got) if s == FAIL]
        if failed:
            r.status, r.detail = FAIL, "failed: " + ", ".join(failed)
        elif NOT_RUN in got:
            r.status = NOT_RUN
            r.detail = "no result yet: " + ", ".join(t for t, s in zip(r.matched, got) if s == NOT_RUN)
        elif any(t in stale.get(r.tier, {}) for t in r.matched):
            old = [t for t in r.matched if t in stale[r.tier]]
            r.status = STALE
            r.detail = f"{stale[r.tier][old[0]]} ({', '.join(old)})"
        elif SKIP in got:
            r.status, r.detail = SKIP, "skipped: " + ", ".join(t for t, s in zip(r.matched, got) if s == SKIP)
        else:
            r.status, r.detail = PASS, ", ".join(r.matched)


def orphans(reqs: list[Requirement], found: dict[str, set[str]]) -> dict[str, list[str]]:
    """Tests that no requirement points at. Not an error, but worth a look: either
    the FSD is missing a requirement, or the test is noise."""
    used = {t.partition("@")[0] for r in reqs for t in r.matched}
    return {tier: sorted(n - used) for tier, n in found.items() if n - used}


# ------------------------------------------------------------------- output
def render(reqs: list[Requirement], when: dict[str, str], orphan: dict[str, list[str]]) -> str:
    counts: dict[str, int] = {}
    for r in reqs:
        counts[r.status] = counts.get(r.status, 0) + 1
    out = ["# Requirement status", "",
           f"Generated by `tools/trace.py` on {time.strftime('%Y-%m-%d %H:%M')}. "
           "Results are from the last run of each tier:", ""]
    for tier in AUTO_TIERS:
        out.append(f"- {tier}: {when.get(tier, 'never run on this machine')}")
    out += ["", "| ID | Tier | Status | Detail | Requirement |", "|---|---|---|---|---|"]
    for r in reqs:
        text = r.text if len(r.text) <= 70 else r.text[:67] + "..."
        out.append(f"| {r.rid} | {r.tier} | {r.status} | {r.detail} | {text} |")
    out += ["", "**Summary:** " + ", ".join(f"{k} {v}" for k, v in sorted(counts.items())) if counts
            else "**Summary:** no requirements found in docs/FSD.md"]
    if orphan:
        out += ["", "Tests not referenced by any requirement: " +
                "; ".join(f"{tier}: {', '.join(n)}" for tier, n in orphan.items())]
    return "\n".join(out) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("only", nargs="*", metavar="REQ-ID", help="limit to these requirement IDs")
    ap.add_argument("--root", default=".", help="project folder (default: current)")
    ap.add_argument("--fsd", default="docs/FSD.md")
    ap.add_argument("--strict", action="store_true", help="fail on NO TEST / FAIL / BAD TIER")
    ap.add_argument("--require-run", action="store_true", help="--strict, and NOT RUN / SKIPPED fail too")
    ap.add_argument("--out", help="also write the matrix to this Markdown file")
    ap.add_argument("--hash", choices=sorted(SOURCES), help="print a source fingerprint and exit")
    ap.add_argument("--write-build-id", metavar="FILE",
                    help="write the firmware fingerprint as FW_BUILD_ID into FILE and exit")
    args = ap.parse_args(argv)

    root = Path(args.root).resolve()
    if args.hash:
        print(src_hash(root, args.hash))
        return 0
    if args.write_build_id:
        print(f"firmware build id: {write_build_id(root, root / args.write_build_id)}")
        return 0
    fsd = root / args.fsd
    if not fsd.is_file():
        print(f"trace: {fsd} not found", file=sys.stderr)
        return 4
    reqs = parse_fsd(fsd.read_text(encoding="utf-8"))
    dupes = sorted({r.rid for r in reqs if sum(x.rid == r.rid for x in reqs) > 1})
    found = discover(root)
    results, when, stale = load_results(root)
    evaluate(reqs, found, results, stale)
    orphan = orphans(reqs, found)

    if args.only:
        unknown = [i for i in args.only if i not in {r.rid for r in reqs}]
        if unknown:
            print(f"trace: not in the FSD: {', '.join(unknown)}", file=sys.stderr)
            return 4
        reqs = [r for r in reqs if r.rid in args.only]
        orphan = {}

    text = render(reqs, when, orphan)
    if dupes:
        text += f"\nWARNING: duplicate requirement IDs: {', '.join(dupes)}\n"
    print(text, end="")
    if args.out:
        Path(args.out).write_text(text, encoding="utf-8")

    blocking = BLOCKING_RUN if args.require_run else BLOCKING_STRICT if args.strict else set()
    bad = [r for r in reqs if r.status in blocking]
    if dupes and blocking:
        return 1
    if bad:
        print(f"TRACE:FAIL {len(bad)} requirement(s) not proven: {', '.join(r.rid for r in bad)}")
        return 1
    if blocking:
        print("TRACE:OK")
    return 0


if __name__ == "__main__":
    sys.exit(main())
